<?php

namespace App\Console\Commands;

use App\Models\User;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\Hash;
use Illuminate\Support\Str;

class MakeAdminCommand extends Command
{
    /**
     * The name and signature of the console command.
     *
     * @var string
     */
    protected $signature = 'make:admin
                            {email? : Email pengguna yang ingin dijadikan admin atau dibuat baru}
                            {--name= : Nama lengkap pengguna jika membuat akun admin baru}
                            {--password= : Kata sandi untuk akun admin baru atau untuk mereset kata sandi}
                            {--assign-only : Hanya tetapkan peran admin pada akun yang sudah ada (tidak membuat akun baru)}
                            {--revoke : Cabut hak akses admin dan kembalikan peran akun menjadi user}';

    /**
     * The console command description.
     *
     * @var string
     */
    protected $description = 'Tetapkan peran Administrator pada akun yang sudah ada atau buat akun Admin baru secara aman';

    /**
     * Execute the console command.
     */
    public function handle(): int
    {
        $email = $this->argument('email');

        // Jika email tidak diberikan via argumen, minta input interaktif
        if (! $email) {
            $email = $this->ask('Masukkan alamat email pengguna:');
        }

        $email = strtolower(trim((string) $email));

        if (! filter_var($email, FILTER_VALIDATE_EMAIL)) {
            $this->error("Format email '{$email}' tidak valid.");
            return 1;
        }

        $user = User::where('email', $email)->first();
        $isRevoke = $this->option('revoke');

        // Skenario 1: Cabut hak akses admin (--revoke)
        if ($isRevoke) {
            if (! $user) {
                $this->error("Pengguna dengan email '{$email}' tidak ditemukan.");
                return 1;
            }

            $user->role = 'user';
            $user->save();

            $this->info("Hak akses Administrator untuk pengguna {$user->name} ({$user->email}) berhasil dicabut.");
            $this->line("Peran pengguna saat ini: <comment>user</comment>.");
            return 0;
        }

        // Skenario 2: Pengguna sudah terdaftar di database -> Promosikan menjadi Admin
        if ($user) {
            $user->role = 'admin';
            $user->is_verified = true;

            $password = $this->option('password');
            if ($password) {
                if (strlen($password) < 8) {
                    $this->error('Kata sandi minimal harus 8 karakter.');
                    return 1;
                }
                $user->password = Hash::make($password);
                $this->comment('Kata sandi pengguna juga telah diperbarui.');
            }

            $user->save();

            $this->info("Pengguna {$user->name} ({$user->email}) berhasil ditetapkan sebagai Administrator!");
            $this->table(
                ['ID', 'Nama', 'Email', 'Role', 'Status Verifikasi'],
                [[$user->id, $user->name, $user->email, $user->role, 'Terverifikasi (true)']]
            );
            return 0;
        }

        // Skenario 3: Pengguna belum terdaftar
        if ($this->option('assign-only')) {
            $this->error("Pengguna dengan email '{$email}' belum terdaftar di database.");
            $this->line('Hapus flag --assign-only jika Anda ingin membuat akun admin baru.');
            return 1;
        }

        $this->warn("Pengguna dengan email '{$email}' belum ada di database.");
        
        // Konfirmasi jika di mode interaktif
        if ($this->input->isInteractive() && ! $this->confirm('Apakah Anda ingin membuat akun Admin baru dengan email ini?', true)) {
            $this->line('Operasi dibatalkan.');
            return 0;
        }

        $name = $this->option('name');
        if (! $name) {
            $name = $this->input->isInteractive() 
                ? $this->ask('Masukkan nama lengkap Admin:', 'Administrator ActGiving')
                : 'Administrator ActGiving';
        }

        $password = $this->option('password');
        $autoGenerated = false;

        if (! $password) {
            if ($this->input->isInteractive()) {
                $password = $this->secret('Masukkan kata sandi untuk akun Admin baru (minimal 8 karakter):');
            }
            
            if (! $password) {
                // Generate kata sandi acak yang aman jika tidak diisi
                $password = Str::random(12);
                $autoGenerated = true;
            }
        }

        if (strlen($password) < 8) {
            $this->error('Kata sandi minimal harus 8 karakter.');
            return 1;
        }

        $newAdmin = User::create([
            'name' => trim((string) $name),
            'email' => $email,
            'password' => Hash::make($password),
            'role' => 'admin',
            'is_verified' => true,
            'email_verified_at' => now(),
        ]);

        $this->info("Akun Administrator baru berhasil dibuat!");
        $this->table(
            ['ID', 'Nama', 'Email', 'Role', 'Status Verifikasi'],
            [[$newAdmin->id, $newAdmin->name, $newAdmin->email, $newAdmin->role, 'Terverifikasi (true)']]
        );

        if ($autoGenerated) {
            $this->warn("Kata sandi yang dibuat otomatis: {$password}");
            $this->line("Harap simpan kata sandi ini dengan aman atau ubah setelah login pertama.");
        }

        return 0;
    }
}
